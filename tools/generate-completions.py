"""Generate the editor's API symbol table from the documented SDK and registry."""
import argparse
import importlib.util
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location("physim_reference", ROOT / "tools/generate-reference.py")
reference = importlib.util.module_from_spec(spec)
sys.path.insert(0,str(ROOT / "tools"))
try:
    spec.loader.exec_module(reference)
finally:
    sys.path.pop(0)


def symbols():
    entries = {}
    def add(language, name, module, signature, kind, instance=False):
        key = (language, name)
        if key not in entries:
            entries[key] = (name, module, re.sub(r"\s+", " ", signature).strip(), kind, language, instance)
    for module in sorted(reference.MODULES):
        source = (ROOT / "include/physim" / (module + ".h")).read_text(encoding="utf-8")
        for name in re.findall(r"^\s*#\s*define\s+(PS_\w+)", source, re.M):
            add(False, name, module, name, "PS_COMPLETION_VALUE")
        if "typedef max_align_t ps_memory_alignment;" in source:
            add(False, "ps_memory_alignment", module, "typedef max_align_t ps_memory_alignment;", "PS_COMPLETION_TYPE")
        for code, _ in reference.declarations(source):
            if code.startswith("typedef"):
                aliases = re.findall(r"\(\s*\*\s*(ps_\w+)\s*\)", code)
                aliases += re.findall(r"\b(ps_\w+)\s*;\s*$", code)
                for name in aliases:
                    add(False, name, module, code, "PS_COMPLETION_TYPE")
            else:
                functions = re.findall(r"\b(ps_\w+)\s*\(", code)
                if functions:
                    add(False, functions[0], module, code, "PS_COMPLETION_FUNCTION")
            for name in re.findall(r"\b(PS_\w+)\b", code):
                add(False, name, module, name, "PS_COMPLETION_VALUE")
    page = reference.language_reference()
    registry=(ROOT / "src/language/builtins.c").read_text(encoding="utf-8")
    factories=registry.split('factories[] =',1)[1].split('const ps_lang_builtin *ps_lang_builtin_find',1)[0]
    static_calls={owner+'.'+method for owner,method in re.findall(r'\{\s*"(\w+)"\s*,\s*"(\w+)"\s*,\s*"\w+"\s*\}',factories)}
    static_calls.update(('Int64.parse','Float64.parse'))
    for heading, body in re.findall(r"^## ([^\n]+)\n(.*?)(?=^## |\Z)", page, re.M | re.S):
        code = re.search(r"```text\n([^`]+)\n```", body)
        if not code or heading in ("Aufrufbeispiel", "Werte und Grenzen"):
            continue
        name = heading.split("(", 1)[0]
        assert re.fullmatch(r"\w+(?:\.\w+)*", name), name
        add(True, name, "Physim", code.group(1), "PS_COMPLETION_FUNCTION",'.' in name and name not in static_calls)
        if "." in name and name[0].isupper():
            owner=name.split(".",1)[0]
            add(True,owner,"Physim",owner,"PS_COMPLETION_TYPE")
    checker=(ROOT / "src/language/checker.c").read_text(encoding="utf-8")
    types=checker.split("static int builtin_type_name(",1)[1].split("};",1)[0]
    for type_name in re.findall(r'"([A-Za-z0-9]+)"',types):
        add(True,type_name,"Physim",type_name,"PS_COMPLETION_TYPE")
    return [entries[key] for key in sorted(entries)]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    rows = symbols()
    contents = "/* Generated by tools/generate-completions.py. Do not edit. */\n"
    for name, module, signature, kind, language, instance in rows:
        fields = [json.dumps(s, ensure_ascii=False) for s in (name, module, signature)]
        contents += "{" + ", ".join(fields + [kind, "true" if language else "false", "true" if instance else "false"]) + "},\n"
    output = ROOT / "app/completion_symbols.inc"
    if args.check:
        if not output.is_file() or output.read_text(encoding="utf-8") != contents:
            raise SystemExit("API completion symbols are stale; run tools/generate-completions.py")
    else:
        output.write_text(contents, encoding="utf-8")
    print(f"{sum(not row[4] for row in rows)} C and {sum(row[4] for row in rows)} Physim completion symbols verified")


if __name__ == "__main__":
    main()
