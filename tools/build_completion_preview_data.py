"""Freeze the local completion catalog and small reference excerpts for D09."""
from pathlib import Path
import argparse
import hashlib
import json
import re

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / 'docs/visuals/completion-options/catalog.js'


def build():
    source = ROOT / 'app/completion_symbols.inc'
    pattern = re.compile(r'^\{"((?:[^"\\]|\\.)*)", "((?:[^"\\]|\\.)*)", "((?:[^"\\]|\\.)*)", PS_COMPLETION_(FUNCTION|TYPE|VALUE), (true|false), (true|false)\},?$', re.M)
    entries = pattern.findall(source.read_text(encoding='utf-8'))
    assert entries, 'No catalog entries found'
    modules = {}
    hashes = {'app/completion_symbols.inc': hashlib.sha256(source.read_bytes().replace(b'\r\n', b'\n')).hexdigest()}
    data = []
    for name, module, signature, kind, language, instance in entries:
        # Catalog strings use JSON-compatible escaping in the current source.
        name, module, signature = [json.loads('"' + text + '"') for text in (name, module, signature)]
        relative = 'docs/reference/language-library.md' if language == 'true' else f'docs/reference/{module}.md'
        path = ROOT / relative
        if relative not in modules:
            text = path.read_text(encoding='utf-8') if path.exists() else ''
            modules[relative] = text
            if path.exists():
                hashes[relative] = hashlib.sha256(path.read_bytes().replace(b'\r\n', b'\n')).hexdigest()
        text = modules[relative]
        section = re.search(r'^#{2,3} ' + re.escape(name) + r'\s*\n(.*?)(?=^#{2,3} |\Z)', text, re.M | re.S)
        summary, parameters = '', []
        if section:
            content = re.sub(r'```[^\n]*\n.*?```', '', section.group(1), flags=re.S)
            for paragraph in re.split(r'\n\s*\n', content):
                paragraph = paragraph.strip()
                if paragraph and not paragraph.startswith(('|', '#', '[', 'Beispiel für')):
                    summary = ' '.join(paragraph.split())
                    break
            table = re.search(r'^\| Argument \|[^\n]*\n\|[^\n]*\n((?:\|[^\n]*\n?)+)', content, re.M)
            if table:
                for row in table.group(1).splitlines()[:2]:
                    cells = [cell.strip() for cell in row.strip('|').split('|')]
                    if len(cells) == 2:
                        parameters.append(cells)
        data.append(dict(name=name, module=module, signature=signature, kind=kind.lower(), language=language == 'true', instance=instance == 'true', summary=summary, parameters=parameters, reference=relative, documented=bool(section)))
    assert len(data) == sum(line.startswith('{') for line in source.read_text(encoding='utf-8').splitlines()), 'Unparsed catalog row'
    return '// Generated by tools/build_completion_preview_data.py; local fixture, not a runtime documentation loader.\nwindow.PHYSIM_COMPLETION_DATA = ' + json.dumps({'symbols': data, 'sources': hashes}, ensure_ascii=False, separators=(',', ':')) + ';\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    content = build()
    if args.check:
        assert TARGET.read_text(encoding='utf-8') == content, 'D09 catalog fixture is stale'
        print('D09 catalog and reference fixture matches local sources.')
    else:
        TARGET.parent.mkdir(parents=True, exist_ok=True)
        TARGET.write_text(content, encoding='utf-8')
        print(f'Wrote {TARGET.relative_to(ROOT)} ({len(content.encode("utf-8"))} bytes).')
